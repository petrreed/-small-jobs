# --- Hallucination Prevention Mechanism Start ---
def check_hallucination_grounding(generated_text, retrieved_context_list, confidence_threshold=0.3):
    """A basic heuristic to check if generated text is grounded in retrieved context."""
    context_keywords = set()
    for doc in retrieved_context_list:
        # Simple word tokenization and lowercasing
        context_keywords.update(re.findall(r'\b\w+\b', doc.lower()))

    generated_keywords = set(re.findall(r'\b\w+\b', generated_text.lower()))

    # Calculate overlap: how many generated keywords are in the context?
    overlap_count = len(generated_keywords.intersection(context_keywords))
    # Avoid division by zero if generated_keywords is empty
    if len(generated_keywords) == 0:
        return True, "No keywords generated, cannot assess grounding."

    grounding_score = overlap_count / len(generated_keywords)

    if grounding_score < confidence_threshold:
        return False, f"Potential hallucination detected (grounding score: {grounding_score:.2f}). Generated text contains information not strongly present in the retrieved context."
    else:
        return True, f"Generated text appears grounded in the context (grounding score: {grounding_score:.2f})."


