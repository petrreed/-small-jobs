# Define reciprocal_rank_fusion function for Hybrid Fusion
def reciprocal_rank_fusion(results_lists, k=60):
    """Applies Reciprocal Rank Fusion to a list of ranked lists of document IDs."""
    fused_ranks = {}
    for results in results_lists:
        for rank, doc_id in enumerate(results):
            if doc_id not in fused_ranks:
                fused_ranks[doc_id] = 0
            fused_ranks[doc_id] += 1 / (k + rank + 1)
    sorted_fused_ranks = sorted(fused_ranks.items(), key=lambda item: item[1], reverse=True)
    return [doc_id for doc_id, _ in sorted_fused_ranks] # Return top N based on fused scores

